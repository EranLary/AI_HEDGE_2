def test_reuse_accepts_fresh_success_with_matching_config(tmp_path):
    now = datetime(2026, 5, 27, tzinfo=timezone.utc)
    old_dir = tmp_path / "outputs" / "_site_runs" / "old" / "TEST"
    new_dir = tmp_path / "outputs" / "_site_runs" / "new" / "TEST"
    old_dir.mkdir(parents=True)
    new_dir.mkdir(parents=True)
    payload = {
        "status": "success",
        "ticker": "TEST",
        "generated_at": (now - timedelta(days=2)).isoformat(),
        "adapter_version": ta.ADAPTER_VERSION,
        "config_version": ta.CONFIG_VERSION,
        "selected_analysts": ta.SELECTED_ANALYSTS,
        "fundamentals_report": "fresh enough",
    }
    artifact = old_dir / "TEST_trading_agents.json"
    artifact.write_text(json.dumps(payload), encoding="utf-8")
    (old_dir / "TEST_trading_agents.txt").write_text("text", encoding="utf-8")

    found = ta.find_reusable_trading_agents_artifact(output_dir=new_dir, ticker="TEST", now=now)

    assert found is not None
    assert found[0] == artifact.resolve()


def test_reuse_rejects_stale_failure_and_version_mismatches(tmp_path):
    now = datetime(2026, 5, 27, tzinfo=timezone.utc)
    new_dir = tmp_path / "outputs" / "_site_runs" / "new" / "TEST"
    new_dir.mkdir(parents=True)
    cases = [
        ("stale", "success", now - timedelta(days=10), ta.ADAPTER_VERSION, ta.CONFIG_VERSION),
        ("failed", "unavailable", now - timedelta(days=1), ta.ADAPTER_VERSION, ta.CONFIG_VERSION),
        ("adapter", "success", now - timedelta(days=1), "old-adapter", ta.CONFIG_VERSION),
        ("config", "success", now - timedelta(days=1), ta.ADAPTER_VERSION, "old-config"),
    ]
    for name, status, generated_at, adapter_version, config_version in cases:
        directory = tmp_path / "outputs" / "_site_runs" / name / "TEST"
        directory.mkdir(parents=True)
        payload = {
            "status": status,
            "ticker": "TEST",
            "generated_at": generated_at.isoformat(),
            "adapter_version": adapter_version,
            "config_version": config_version,
            "selected_analysts": ta.SELECTED_ANALYSTS,
        }
        (directory / "TEST_trading_agents.json").write_text(json.dumps(payload), encoding="utf-8")

    found = ta.find_reusable_trading_agents_artifact(output_dir=new_dir, ticker="TEST", now=now)

    assert found is None


def test_propagate_helper_supports_v024_signature_without_asset_type():
    class Graph:
        def __init__(self):
            self.calls = []

        def propagate(self, ticker, trade_date):
            self.calls.append((ticker, trade_date))
            return {"fundamentals_report": "ok"}, "decision"

    graph = Graph()

    state, decision = ta._propagate_trading_agents_graph(graph, "AAPL", "2026-05-27")

    assert graph.calls == [("AAPL", "2026-05-27")]
    assert state["fundamentals_report"] == "ok"
    assert decision == "decision"


def test_propagate_helper_keeps_asset_type_when_supported():
    class Graph:
        def __init__(self):
            self.calls = []

        def propagate(self, ticker, trade_date, *, asset_type):
            self.calls.append((ticker, trade_date, asset_type))
            return {"fundamentals_report": "ok"}, "decision"

    graph = Graph()

    ta._propagate_trading_agents_graph(graph, "AAPL", "2026-05-27")

    assert graph.calls == [("AAPL", "2026-05-27", "stock")]
