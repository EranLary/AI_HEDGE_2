def test_required_target_portfolio_manager_contract():
    class FakeStructured:
        def __init__(self, schema, owner):
            self.schema = schema
            self.owner = owner

        def invoke(self, prompt):
            self.owner.prompt = prompt
            return self.schema(
                rating="Underweight",
                executive_summary="Reduce exposure.",
                investment_thesis="Risk outweighs reward.",
                price_target=210,
                time_horizon="6 months",
            )

    class FakeLlm:
        def __init__(self):
            self.schema = None
            self.prompt = ""

        def with_structured_output(self, schema):
            self.schema = schema
            return FakeStructured(schema, self)

        def invoke(self, _prompt):
            raise AssertionError("structured output should be used")

    llm = FakeLlm()
    node = ta._create_required_target_portfolio_manager(llm)
    state = {
        "company_of_interest": "IBM",
        "investment_plan": "Reduce exposure.",
        "trader_investment_plan": "Sell into strength.",
        "risk_debate_state": {
            "history": "Risks dominate.",
            "aggressive_history": "Aggressive view.",
            "conservative_history": "Conservative view.",
            "neutral_history": "Neutral view.",
            "current_aggressive_response": "",
            "current_conservative_response": "",
            "current_neutral_response": "",
            "count": 3,
        },
    }

    result = node(state)

    assert llm.schema.model_fields["price_target"].is_required()
    assert llm.schema.model_fields["time_horizon"].is_required()
    assert "Always provide one numeric **Price Target**" in llm.prompt
    assert "**Price Target**: 210.0" in result["final_trade_decision"]
    assert "**Time Horizon**: 6 months" in result["final_trade_decision"]


def test_deepseek_reasoner_skips_structured_tool_choice_for_managers():
    class Response:
        content = "**Rating**: Hold\n\n**Price Target**: 210\n\n**Time Horizon**: 6 months"

    class FakeReasoner:
        model_name = "deepseek-reasoner"

        def __init__(self):
            self.invocations = 0

        def with_structured_output(self, _schema):
            raise AssertionError("reasoner must not bind structured tool output")

        def invoke(self, _prompt):
            self.invocations += 1
            return Response()

    llm = FakeReasoner()
    assert ta._supports_structured_output(llm) is False

    portfolio_node = ta._create_required_target_portfolio_manager(llm)
    portfolio_result = portfolio_node(
        {
            "company_of_interest": "IBM",
            "investment_plan": "Balanced plan.",
            "trader_investment_plan": "Wait.",
            "risk_debate_state": {
                "history": "Balanced risks.",
                "aggressive_history": "",
                "conservative_history": "",
                "neutral_history": "",
                "current_aggressive_response": "",
                "current_conservative_response": "",
                "current_neutral_response": "",
                "count": 3,
            },
        }
    )
    assert "**Price Target**: 210" in portfolio_result["final_trade_decision"]

    research_node = ta._create_deepseek_compatible_research_manager(llm)
    research_result = research_node(
        {
            "company_of_interest": "IBM",
            "investment_debate_state": {
                "history": "Bull and bear evidence.",
                "bear_history": "Bear evidence.",
                "bull_history": "Bull evidence.",
                "count": 2,
            },
        }
    )
    assert "**Rating**: Hold" in research_result["investment_plan"]
    assert llm.invocations == 2


